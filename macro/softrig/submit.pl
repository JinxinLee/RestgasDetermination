sub pbarmom
{
	my $mp0  = 0.938272;
	my $minp = 0.0;
	my $s    = $_[0]*$_[0];

	if (sqrt($s)>2.*$mp0) {$minp = sqrt(($s-2.*$mp0*$mp0)*($s-2.*$mp0*$mp0)/(4.*$mp0*$mp0)-$mp0*$mp0);}	
	
	return $minp;
}
